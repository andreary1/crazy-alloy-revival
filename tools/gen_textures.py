def box(img, u, v, w, h, d, side, top=None, front=None, bottom=None):
    """Paints a model cube's UV net. side/top/front/bottom are callables (x, y, face_w, face_h) -> color or a color."""
    px = img.load()
    def fill(x0, y0, fw, fh, col):
        for y in range(fh):
            for x in range(fw):
                c = col(x, y, fw, fh) if callable(col) else col
                if c is not None and 0 <= x0 + x < img.width and 0 <= y0 + y < img.height:
                    px[x0 + x, y0 + y] = c
    top = top or side; front = front or side; bottom = bottom or side
    fill(u + d, v, w, d, top)
    fill(u + d + w, v, w, d, bottom)
    fill(u, v + d, d, h, side)
    fill(u + d, v + d, w, h, front)
    fill(u + d + w, v + d, d, h, side)
    fill(u + 2 * d + w, v + d, w, h, side)

