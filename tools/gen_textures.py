    def stripes(x, y, w, h):
        return STRIPE if ((x + y) // 2) % 2 == 0 else white
    dog = Image.new("RGBA", (64, 32), (0, 0, 0, 0))
    box(dog, 0, 0, 6, 6, 12, stripes)
    def face(x, y, w, h):
        if y == 2 and x in (1, 4):
            return dark
        if y == 2 and x in (0, 5):
            return white
        return pink
    box(dog, 0, 18, 6, 6, 4, pink, front=face)
    def snout(x, y, w, h):
        return dark if (y == 0 and x == 1) else white
    box(dog, 20, 18, 3, 3, 3, white, front=snout)
    box(dog, 36, 0, 2, 2, 1, hexc("d9487a"))
    box(dog, 36, 18, 2, 6, 2, white, bottom=hexc("d9487a"))
    box(dog, 44, 18, 2, 2, 6, stripes)
    save(dog, "entity/candy_tube_dog.png")

    lg = Image.new("RGBA", (64, 32), (0, 0, 0, 0))
    red = hexc("ff4f7b")
    def swirl(x, y, w, h):
        cx, cy = (w - 1) / 2, (h - 1) / 2
        a = math.atan2(y - cy, x - cx)
        r = math.hypot(x - cx, y - cy)
        return white if int((a / math.tau * 4 + r / 2.2)) % 2 == 0 else red
    def lg_face(x, y, w, h):
        if y == 4 and x in (3, 6):
            return dark
        if y == 6 and 3 <= x <= 6:
            return dark if x in (3, 6) or y == 7 else hexc("8a1c3a")
        return swirl(x, y, w, h)
    box(lg, 0, 0, 10, 10, 2, red, front=lg_face, top=hexc("e8456f"))
    # back face of the disc keeps the swirl
    px = lg.load()
    for y in range(10):
        for x in range(10):
            px[2 + 2 + 10 + x, 2 + y] = swirl(x, y, 10, 10)
    box(lg, 0, 12, 4, 10, 3, white)
    box(lg, 16, 12, 2, 8, 2, hexc("f5e6ee"), bottom=hexc("ffc0df"))
    box(lg, 24, 12, 2, 6, 2, hexc("f5e6ee"), bottom=hexc("c75a86"))
