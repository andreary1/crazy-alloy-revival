#!/usr/bin/env python3
"""Procedural placeholder textures for Crazy Alloy: Revival (stage 1).

All textures here are ORIGINAL and PROVISIONAL: they are generated by this script (no vanilla or
original-mod pixels are copied) so the mod is playable and visually consistent until hand-drawn art
replaces them. Palette and 16x16 resolution follow vanilla conventions.
Run: python3 tools/gen_textures.py   (requires Pillow)
"""
import math, os, random
from PIL import Image, ImageDraw

NS = "crazyalloy_revival"
T = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "main", "resources", "assets", NS, "textures")
R = random.Random(20261001)

def hexc(h, a=255):
    h = h.lstrip("#")
    return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), a)

def shade(c, f):
    return tuple(max(0, min(255, int(v * f))) for v in c[:3]) + (c[3],)

HAND_PAINTED = {l.strip() for l in open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "hand_painted.txt"), encoding="utf-8")
                if l.strip() and not l.startswith("#")}

def save(img, rel):
    if rel in HAND_PAINTED:
        return  # the owner's hand-painted texture wins over the generated placeholder
    p = os.path.join(T, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    img.save(p)

def noise(size, palette, weights=None):
    img = Image.new("RGBA", (size, size))
    px = img.load()
    for y in range(size):
        for x in range(size):
            px[x, y] = R.choices(palette, weights=weights)[0]
    return img

